/* One field contract for GitHub feedback, generated forms and URL prefills.
 * No state/storage access: environment capture is an explicit whitelist. */
export const FEEDBACK_FIELDS = Object.freeze([
  { id: 'category', type: 'dropdown', options: ['interface', 'build', 'catalog', 'other'], required: true },
  { id: 'interface', type: 'dropdown', options: ['desktop', 'mobile', 'tablet', 'other'], required: true },
  { id: 'description', type: 'textarea', required: true },
  { id: 'expected', type: 'textarea' },
  { id: 'steps', type: 'textarea' },
  { id: 'run', type: 'input' },
]);

export function feedbackEnvironment({ source, branch, target, version, commit, catalogCode, catalogData,
  sourceCommit, catalogState, language, requestedLanguage, userAgent, platform, width, height }) {
  return {
    Source: source || '', Branch: branch || '',
    'Target System': target?.system || '', Subtarget: target?.subtarget || '',
    'Target Profile': target?.profile || '',
    'Web Version': version || '', 'Web Commit': commit || '',
    'Catalog Code': catalogCode || '', 'Catalog Data': catalogData || '',
    'Source Commit': sourceCommit || '', 'Catalog State': catalogState || '', Language: language || '',
    'Requested Language': requestedLanguage || language || '',
    Browser: String(userAgent || ''), Platform: String(platform || ''),
    Viewport: `${Math.round(Number(width) || 0)} × ${Math.round(Number(height) || 0)}`,
  };
}

export const feedbackLanguage = language => language === 'zh-CN' ? 'zh-CN' : 'en';
export function feedbackInterface(userAgent = '', platform = '', touchPoints = 0) {
  if (/iPad|Tablet/i.test(userAgent) || (platform === 'MacIntel' && touchPoints > 1)) return 'tablet';
  if (/iPhone|iPod|Android.*Mobile/i.test(userAgent)) return 'mobile';
  return /Android/i.test(userAgent) ? 'tablet' : 'desktop';
}

export function feedbackReport(values, environment, translate) {
  const sections = FEEDBACK_FIELDS.flatMap(field => {
    const value = String(values[field.id] || '').trim();
    if (!value) return [`### ${translate(`feedback.${field.id}`)}\n\n<!-- ${translate(`feedback.${field.id}.hint`)} -->`];
    const text = field.options ? translate(`feedback.${field.id}.${value}`) : value;
    return [`### ${translate(`feedback.${field.id}`)}\n\n${text}`];
  });
  sections.push(`### ${translate('feedback.environment')}\n\n\`\`\`json\n${JSON.stringify(environment, null, 2)}\n\`\`\``);
  return sections.join('\n\n');
}

// Stable form IDs are also the URL-prefill contract. Plain Issues remain usable
// until the native template reaches the repository's default branch.
export function feedbackIssueLink({ repository, environment, interfaceType, nativeTemplate = false, language, translate, identity }) {
  const { githubIssueUrl, ISSUE_URL_LIMIT } = identity;
  const locale = feedbackLanguage(language);
  const report = feedbackReport({ category: 'other', interface: interfaceType }, environment, translate);
  const title = '[feedback] ' + translate('feedback.title');
  const parameters = nativeTemplate ? { title, template: `feedback.${locale}.yml`,
    interface: translate(`feedback.interface.${interfaceType}`), environment: JSON.stringify(environment, null, 2) }
    : { title, body: report };
  const url = githubIssueUrl(repository, parameters);
  return { url: url.length <= ISSUE_URL_LIMIT ? url : githubIssueUrl(repository, { title }),
    report, overflow: url.length > ISSUE_URL_LIMIT };
}

export function createFeedbackTemplateResolver({ issueUrl, fetchImpl = globalThis.fetch, timeoutMs = 2000 } = {}) {
  const cache = new Map();
  return (repository, language) => {
    issueUrl(repository);
    const filename = `feedback.${feedbackLanguage(language)}.yml`;
    const key = `${repository}/${filename}`;
    if (!cache.has(key)) cache.set(key, (async () => {
      try {
        const response = await fetchImpl(`https://api.github.com/repos/${repository}/contents/.github/ISSUE_TEMPLATE/${filename}`,
          { credentials: 'omit', signal: AbortSignal.timeout(timeoutMs) });
        if (!response.ok) return false;
        const file = await response.json();
        return file.type === 'file' && file.name === filename;
      } catch { return false; }
    })());
    return cache.get(key);
  };
}

export function feedbackIssueForm(translate) {
  const scalar = value => JSON.stringify(value);
  const lines = ['# Generated by tools/gen-i18n.mjs; do not edit.',
    `name: ${scalar(translate('feedback.title'))}`,
    `description: ${scalar(translate('feedback.formDescription'))}`, 'title: "[feedback] "', 'body:',
    '  - type: markdown', '    attributes:', `      value: ${scalar(translate('feedback.privacy'))}`];
  for (const field of [...FEEDBACK_FIELDS, { id: 'environment', type: 'textarea' }]) {
    lines.push(`  - type: ${field.type}`, `    id: ${field.id}`, '    attributes:',
      `      label: ${scalar(translate(`feedback.${field.id}`))}`);
    if (field.options) {
      lines.push('      options:', ...field.options.map(option => `        - ${scalar(translate(`feedback.${field.id}.${option}`))}`));
    } else if (field.id === 'environment') lines.push('      render: json');
    else lines.push(`      placeholder: ${scalar(translate(`feedback.${field.id}.hint`))}`);
    if (field.required) lines.push('    validations:', '      required: true');
  }
  return lines.join('\n') + '\n';
}
