/* Shared feedback fields for the browser, generated Issue Forms and tests.
 * No state/storage access: environment capture is an explicit whitelist. */
export const FEEDBACK_FIELDS = Object.freeze([
  { id: 'category', type: 'dropdown', options: ['interface', 'build', 'catalog', 'other'], required: true },
  { id: 'interface', type: 'dropdown', options: ['desktop', 'mobile', 'tablet', 'other'], required: true },
  { id: 'description', type: 'textarea', required: true },
  { id: 'expected', type: 'textarea' },
  { id: 'steps', type: 'textarea' },
  { id: 'run', type: 'input' },
]);

export function feedbackEnvironment({ source, branch, target, version, commit, catalogCode, catalogData,
  sourceCommit, catalogState, language, requestedLanguage, userAgent, platform, width, height }) {
  return {
    Source: source || '', Branch: branch || '',
    'Target System': target?.system || '', Subtarget: target?.subtarget || '',
    'Target Profile': target?.profile || '',
    'Web Version': version || '', 'Web Commit': commit || '',
    'Catalog Code': catalogCode || '', 'Catalog Data': catalogData || '',
    'Source Commit': sourceCommit || '', 'Catalog State': catalogState || '', Language: language || '',
    'Requested Language': requestedLanguage || language || '',
    Browser: String(userAgent || ''), Platform: String(platform || ''),
    Viewport: `${Number(width) || 0} × ${Number(height) || 0}`,
  };
}

export function feedbackReport(values, environment, translate) {
  const sections = FEEDBACK_FIELDS.flatMap(field => {
    const value = String(values[field.id] || '').trim();
    if (!value) return [];
    const text = field.options ? translate(`feedback.${field.id}.${value}`) : value;
    return [`### ${translate(`feedback.${field.id}`)}\n\n${text}`];
  });
  sections.push(`### ${translate('feedback.environment')}\n\n\`\`\`json\n${JSON.stringify(environment, null, 2)}\n\`\`\``);
  return sections.join('\n\n');
}

export function feedbackIssueForm(translate) {
  const scalar = value => JSON.stringify(value);
  const lines = ['# Generated by tools/gen-i18n.mjs; do not edit.',
    `name: ${scalar(translate('feedback.title'))}`,
    `description: ${scalar(translate('feedback.formDescription'))}`, 'title: "[feedback] "', 'body:'];
  for (const field of [...FEEDBACK_FIELDS, { id: 'environment', type: 'textarea' }]) {
    lines.push(`  - type: ${field.type}`, `    id: ${field.id}`, '    attributes:',
      `      label: ${scalar(translate(`feedback.${field.id}`))}`);
    if (field.options) {
      lines.push('      options:', ...field.options.map(option => `        - ${scalar(translate(`feedback.${field.id}.${option}`))}`));
    }
    if (field.required) lines.push('    validations:', '      required: true');
  }
  return lines.join('\n') + '\n';
}
